-- ---------------------------------------------------------------------
-- 1) BORRADO (si las tablas no existen, se ignora el error ORA-00942)
--    Orden inverso a las FK: primero las hijas, despues las padres.
-- ---------------------------------------------------------------------
BEGIN
  FOR t IN (SELECT column_value AS nombre
              FROM TABLE(sys.odcivarchar2list('MULTAS','PRESTAMOS','EJEMPLARES',
                                              'LIBROS','AUTORES','SOCIOS'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.nombre || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
END;
/


-- ---------------------------------------------------------------------
-- 2) TABLAS
-- ---------------------------------------------------------------------

-- Personas que pueden pedir libros prestados
CREATE TABLE socios (
  soc_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  dni         VARCHAR2(10)  NOT NULL,
  nombre      VARCHAR2(60)  NOT NULL,
  apellido    VARCHAR2(60)  NOT NULL,
  email       VARCHAR2(100),
  tipo        VARCHAR2(10)  NOT NULL,
  fecha_alta  DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  activo      NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT pk_socios        PRIMARY KEY (soc_id),
  CONSTRAINT uq_socios_dni    UNIQUE (dni),
  CONSTRAINT uq_socios_email  UNIQUE (email),
  CONSTRAINT ck_socios_tipo   CHECK (tipo IN ('ALUMNO','DOCENTE','EXTERNO')),
  CONSTRAINT ck_socios_activo CHECK (activo IN (0,1))
);

CREATE TABLE autores (
  aut_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre        VARCHAR2(100) NOT NULL,
  nacionalidad  VARCHAR2(50),
  CONSTRAINT pk_autores PRIMARY KEY (aut_id)
);

-- El LIBRO es la obra (titulo, ISBN). Cada copia fisica es un EJEMPLAR.
CREATE TABLE libros (
  lib_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  isbn       VARCHAR2(20)  NOT NULL,
  titulo     VARCHAR2(200) NOT NULL,
  anio       NUMBER(4),
  categoria  VARCHAR2(50),
  aut_id     NUMBER        NOT NULL,
  CONSTRAINT pk_libros       PRIMARY KEY (lib_id),
  CONSTRAINT uq_libros_isbn  UNIQUE (isbn),
  CONSTRAINT fk_libros_autor FOREIGN KEY (aut_id) REFERENCES autores (aut_id)
);

CREATE TABLE ejemplares (
  eje_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  lib_id             NUMBER       NOT NULL,
  codigo_inventario  VARCHAR2(20) NOT NULL,
  estado             VARCHAR2(12) DEFAULT 'DISPONIBLE' NOT NULL,
  CONSTRAINT pk_ejemplares        PRIMARY KEY (eje_id),
  CONSTRAINT uq_ejemplares_codigo UNIQUE (codigo_inventario),
  CONSTRAINT fk_ejemplares_libro  FOREIGN KEY (lib_id) REFERENCES libros (lib_id),
  CONSTRAINT ck_ejemplares_estado CHECK (estado IN ('DISPONIBLE','PRESTADO','REPARACION','BAJA'))
);

-- fecha_devolucion NULL  =>  el prestamo todavia esta activo
CREATE TABLE prestamos (
  pre_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  eje_id             NUMBER NOT NULL,
  soc_id             NUMBER NOT NULL,
  fecha_prestamo     DATE   DEFAULT TRUNC(SYSDATE) NOT NULL,
  fecha_vencimiento  DATE   NOT NULL,
  fecha_devolucion   DATE,
  CONSTRAINT pk_prestamos          PRIMARY KEY (pre_id),
  CONSTRAINT fk_prestamos_ejemplar FOREIGN KEY (eje_id) REFERENCES ejemplares (eje_id),
  CONSTRAINT fk_prestamos_socio    FOREIGN KEY (soc_id) REFERENCES socios (soc_id),
  CONSTRAINT ck_prestamos_fechas   CHECK (fecha_vencimiento >= fecha_prestamo)
);

-- Una multa por prestamo devuelto tarde (por eso pre_id es UNIQUE)
CREATE TABLE multas (
  mul_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  pre_id  NUMBER       NOT NULL,
  monto   NUMBER(10,2) NOT NULL,
  pagada  NUMBER(1)    DEFAULT 0 NOT NULL,
  CONSTRAINT pk_multas          PRIMARY KEY (mul_id),
  CONSTRAINT uq_multas_prestamo UNIQUE (pre_id),
  CONSTRAINT fk_multas_prestamo FOREIGN KEY (pre_id) REFERENCES prestamos (pre_id),
  CONSTRAINT ck_multas_monto    CHECK (monto > 0),
  CONSTRAINT ck_multas_pagada   CHECK (pagada IN (0,1))
);


-- ---------------------------------------------------------------------
-- 3) INDICES sobre las FK (Oracle NO los crea solo; aceleran los JOIN)
-- ---------------------------------------------------------------------
CREATE INDEX ix_libros_autor      ON libros (aut_id);
CREATE INDEX ix_ejemplares_libro  ON ejemplares (lib_id);
CREATE INDEX ix_prestamos_socio   ON prestamos (soc_id);
CREATE INDEX ix_prestamos_eje     ON prestamos (eje_id);


